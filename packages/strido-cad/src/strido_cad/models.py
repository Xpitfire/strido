"""Generate the simulation models of Strido from the verified CAD assembly.

Outputs (all regenerated, never hand-edited):
  ros2/strido_description/meshes/<link>.stl     visual meshes per link (vendor parts as convex hulls)
  ros2/strido_description/urdf/strido.urdf     plain URDF, relative mesh paths (PyBullet, MuJoCo, Isaac)
  ros2/strido_description/config/mass_report.yaml  per-link mass/CoM/inertia with the inputs used
  models/mujoco/strido.xml                      MJCF with position servos, IMU and foot sites
The ROS xacro (ros2_control + Gazebo sensors) includes the same link data via
ros2/strido_description/urdf/strido.urdf.xacro, written here as well.

Conventions: REP-103 base frame, Go2 joint names/order, SI units.
"""

