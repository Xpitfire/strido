"""Markdown report of the wiring gate (strido_verify.wiring): findings, cut list, stock."""

CHECK_ORDER = ("reach", "wire stock", "ready-made cables", "hip loop", "port", "through parts", "moving parts")


def _table(findings) -> list[str]:
    lines = ["| Check | Item | Status | Value | Limit | Note |", "|---|---|---|---|---|---|"]
    for finding in findings:
        lines.append(
            f"| {finding.check} | `{finding.item}` | {finding.status} | {finding.value} | {finding.limit} | {finding.note} |"
        )
    return lines


def render(findings, rows, data) -> str:
    counts = {s: sum(f.status == s for f in findings) for s in ("ok", "warn", "fail")}
    cables = sorted({row["cable"] for row in rows})
    lines = [
        "# Wiring check",
        "",
        "Generated by `python -m strido_verify.wiring` from `hardware/wiring.yaml`, routed through the CAD by "
        "`strido_cad.wiring`. "
        f"**{len(cables)} cables in {len(rows)} runs; {len(findings)} checks: {counts['ok']} ok, {counts['warn']} warn, "
        f"{counts['fail']} fail.** How the harness is built: [electronics, wiring and power](../electronics.md#wiring-harness); "
        "background: [cable management](../wiki/making/cable-management.md).",
        "",
        "Clearance uses mesh surface samples in every operating pose (stand, crouch, tall, eight trot phases, hips "
        "out/in); runs through the hip joint are flexible loops checked by length over the full hip range. "
        "Not modelled: bend radii (route corners are drawn sharp) and where a hip loop hangs.",
        "",
    ]
    attention = [f for f in findings if f.status != "ok"]
    if attention:
        lines += ["## Needs attention", "", *_table(sorted(attention, key=lambda f: (f.status != "fail", f.check))), ""]
    lines += ["## Cut list", "", "| Run | Type | From | To | Routed | Cut length |", "|---|---|---|---|---|---|"]
    for row in rows:
        cut = f"{row['cut_mm']} mm" if row["cut_mm"] is not None else "ready-made"
        lines.append(
            f"| `{row['run']}` | {row['type']} | `{row['from']}` | `{row['to']}` | {row['routed_mm']:.0f} mm | {cut} |"
        )
    lines += [
        "",
        f"Cut length = routed length + terminations ({', '.join(f'{k} {v:g} mm' for k, v in data['termination_mm'].items())}) "
        f"+ slack ({data['slack']['fraction']:.0%}, at least {data['slack']['min_mm']:g} mm). Servo-lead branches "
        "(`S-…/power`, `S-…/signal`) are measured from the tie where the lead splits.",
        "",
    ]
    for check in CHECK_ORDER:
        chosen = [f for f in findings if f.check == check]
        if chosen:
            lines += [f"## {check.capitalize()}", "", *_table(chosen), ""]
    return "\n".join(lines)
