"""Markdown report of the strength check (strido_verify.strength): loads, checks, tightening torques.
Formulas are typeset as LaTeX (the documentation site renders $…$)."""

# Plain-text formula of a check (kept plain for the shop's product pages) -> its LaTeX form.
FORMULA_TEX = {
    "F_cr = π² · E · I / (K · L)²": r"F_\mathrm{cr} = \dfrac{\pi^2 E I}{(K L)^2}",
    "S = C0 / F_r": r"S_0 = C_0 / F_r",
    "p = F / (d · L_e)": r"p = \dfrac{F}{d\,L_e}",
    "p = F / (d · t)": r"p = \dfrac{F}{d\,t}",
    "p = T / (n · r · d · t)": r"p = \dfrac{T}{n\,r\,d\,t}",
    "σ = F / A + F · e · sec(L/2 · √(F / E I)) / W": r"\sigma = \dfrac{F}{A} + \dfrac{F\,e}{W}\sec\!\left(\dfrac{L}{2}\sqrt{\dfrac{F}{E I}}\right)",
    "σ = T_knee / (W_inner + W_outer)": r"\sigma = \dfrac{T_\mathrm{knee}}{W_\mathrm{inner} + W_\mathrm{outer}}",
    "σ = T_thigh / W": r"\sigma = T_\mathrm{thigh} / W",
    "τ = F / (1 · A_s)": r"\tau = F / A_s",
    "τ = F / (2 · A_s)": r"\tau = \dfrac{F}{2\,A_s}",
    "τ = T / (n · r · A_s)": r"\tau = \dfrac{T}{n\,r\,A_s}",
}


def render(config: dict, loads: dict, geometry: dict, checks: list, torques: list[dict]) -> str:
    """docs/verification/strength.md from the computed loads (N, N·m), geometry (mm), checks and torques."""
    worst = min(checks, key=lambda c: c.safety)
    counts = {status: sum(c.status == status for c in checks) for status in ("ok", "warn", "fail")}
    material = config["material"]
    lines = [
        "# Strength check",
        "",
        f"Generated by `python -m strido_verify.strength` from `hardware/strength.yaml`, the printed STLs, the leg geometry and the fit report. "
        f"**{len(checks)} checks: {counts['ok']} ok, {counts['warn']} warn, {counts['fail']} fail; lowest safety factor {worst.safety} ({worst.what}).** "
        f"Safety factor S = allowable / actual; fail below {config['safety']['fail_below']}, warn below {config['safety']['warn_below']}. "
        "Formulas and background: [strength, torque and failure](../wiki/making/strength.md).",
        "",
        "## Loads",
        "",
        "| Load | Value | How |",
        "|---|---|---|",
        f"| Foot force, hard landing | {loads['foot_n']:.1f} N | F = {config['loads']['impact_factor']} · m · g / 2, m = {config['loads']['robot_mass_kg']} kg |",
        f"| Thigh and hip joint torque | {loads['thigh_nm']:.2f} N·m | servo stall torque (the largest torque the servo applies) |",
        f"| Knee joint torque | {loads['knee_nm']:.2f} N·m | knee servo at stall through the linkage, largest over the joint range |",
        f"| Knee torque a landing would need | {loads['knee_landing_nm']:.2f} N·m | F_foot · L_tibia ({geometry['tibia']:.0f} mm); beyond the servo's torque the knee is back-driven |",
        f"| Short link force | {loads['short_link_n']:.0f} N | T_stall / (r_arm · sin α), largest over the joint range (r_arm {geometry['arm']:.1f} mm) |",
        f"| Long link force | {loads['long_link_n']:.0f} N | T_crank / (r_crank_b · sin β), largest over the joint range |",
        f"| Knee joint radial force | {loads['knee_joint_n']:.0f} N | F_foot + F_long (upper bound) |",
        "",
        f"Material: {material['name']}: {material['tensile_xy_mpa']} MPa along the layers, {material['layer_adhesion_mpa']} MPa across them. "
        f"Sections count only the {config['print']['wall_mm']} mm walls (infill ignored). Screws: {config['screws']['name']}.",
        "",
        "## Checks",
        "",
        "| Check | Parts | Formula | Actual | Allowable | S | Status |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {c.what} | {', '.join(c.parts)} | ${FORMULA_TEX[c.formula]}$ | {c.actual} {c.unit} | {c.allowable} {c.unit} | **{c.safety}** | {c.status}{' *' if c.note else ''} |"
        for c in checks
    ]
    lines += [line for c in checks if c.note for line in ("", f"\\* **{c.what}:** {c.note}")]  # one paragraph per note
    lines += [
        "",
        "## Tightening torque into printed pilots",
        "",
        rf"Pull-out of a thread-forming screw shears the plastic on a cylinder of the thread diameter: $F = \tau\,\pi\,d\,L_e$ with $\tau = {config['material']['shear_factor']} \times$ layer adhesion (the weakest direction). "
        rf"The torque that produces it is $T = k\,F\,d$ ($k = {config['screws']['torque_factor']}$); tighten to at most half of that.",
        "",
        "| Joint | Part | Thread | Engaged | Pull-out force | Stripping torque | **Tighten to max.** |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {t['joint']} | {t['part']} | {t['thread']} | {t['engaged_mm']} mm | {t['pull_out_n']} N | {t['strip_torque_nm']} N·m | **{t['recommended_torque_nm']} N·m** |"
        for t in torques
    ]
    lines += [
        "",
        "## Limits",
        "",
        "* Static checks with peak loads; fatigue of PETG under millions of steps, creep under a standing load and notch effects at sharp corners are not modelled (hence S ≥ 2).",
        "* Joint torques are the servos' rated stall torque. Back-driving a powered spur-gear servo from outside takes more (about 1 / (η_forward · η_reverse), roughly 1.5–3 × for a multi-stage gearbox [estimate]): a hard impact can exceed these loads.",
        "* The impact factor is an assumption, not a measurement; the servo stall torque is the datasheet value at 6.0 V.",
        "* Bending is taken in the leg plane at the weakest of 41 sections; buckling covers both directions with the stiffness of the sections in series. Bending of the tibias across the leg plane (side loads) is not checked: the two halves are joined, and their combined section is not modelled.",
        "* Hole bearing pressure is compared with the strength along the layers.",
        "* The aluminium horns are not checked (their alloy is not stated by the sellers); they are far stronger than the printed parts they hold.",
        "",
    ]
    return "\n".join(lines)
