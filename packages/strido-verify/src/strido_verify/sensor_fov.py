"""LiDAR scan-plane occlusion and camera field-of-view check on the posed CAD model.

* LiDAR: 720 rays (0.5 deg) in the scan plane from the optical centre, starting
  just outside the sensor dome; any hit on the robot within 12 m is an occlusion.
* Camera: rays over the Camera Module 3 Wide field of view (102 x 67 deg) from the
  lens centre; reports the fraction of the image that sees the robot itself.

Poses: standing, crouched, trotting extremes (swing apex / max stride) and the
hip-abduction limits. Writes build/verify/sensor_fov.json and
docs/verification/sensors.md; exits 1 if the LiDAR plane is occluded anywhere.
"""

import json
import math
import sys

import numpy as np
import trimesh

from strido.workspace import path
from strido_cad import assembly, catalog, parts
from strido_cad.paths import VERIFY_OUT

from .poses import hips_abducted, standing, trot_phases

OUT_JSON = VERIFY_OUT / "sensor_fov.json"
OUT_MD = path("docs/verification/sensors.md")
LIDAR_SELF = ("rplidar_c1", "rplidar_usb_adapter", "lidar_pedestal")
CAMERA_SELF = ("rpi_camera_module_3_wide", "camera_tilt_plate")
CAMERA_HFOV, CAMERA_VFOV = math.radians(102.0), math.radians(67.0)


def poses():
    """Standing, crouched, the two trot extremes and the hip-abduction limits."""
    phases = trot_phases()
    return {
        "stand": standing(0.17),
        "crouch": standing(0.12),
        "trot_swing_apex": phases["trot_6of8"],
        "trot_max_stride": phases["trot_4of8"],
        "hips_abducted": hips_abducted(outward=True),
    }


def scene_mesh(posed, exclude):
    meshes = [assembly.world_mesh(i) for i in posed if i.kind != "reference" and i.part.split("/")[1] not in exclude]
    return trimesh.util.concatenate(meshes)


def lidar_check(mesh):
    cx, cy = parts.LIDAR_CENTRE
    origin_z = parts.TOP_OUTER_Z + parts.PEDESTAL_HEIGHT + 29.8
    angles = np.radians(np.arange(0.0, 360.0, 0.5))
    directions = np.stack([np.cos(angles), np.sin(angles), np.zeros_like(angles)], axis=1)
    origins = np.array([cx, cy, origin_z]) + directions * 28.5
    _locations, index_ray, _ = mesh.ray.intersects_location(origins, directions, multiple_hits=False)
    blocked = sorted(set(int(i) for i in index_ray))
    return [math.degrees(angles[i]) for i in blocked], origin_z


def camera_check(mesh, camera_matrix):
    lens = camera_matrix[:3, 3] + camera_matrix[:3, :3] @ np.array([*parts.vendor.CAMERA_LENS_CENTRE, -8.8])
    forward = -camera_matrix[:3, 2]
    right = -camera_matrix[:3, 1]  # cam y -> -X (robot right is -X when looking forward along -Y)
    up = np.cross(right, forward)
    u = np.tan(np.linspace(-CAMERA_HFOV / 2, CAMERA_HFOV / 2, 61))
    v = np.tan(np.linspace(-CAMERA_VFOV / 2, CAMERA_VFOV / 2, 41))
    directions = np.array([forward + a * right + b * up for b in v for a in u])
    directions /= np.linalg.norm(directions, axis=1, keepdims=True)
    origins = np.repeat(lens[None, :], len(directions), axis=0) + directions * 1.0
    _, index_ray, _ = mesh.ray.intersects_location(origins, directions, multiple_hits=False)
    return len(set(index_ray.tolist())) / len(directions)


def main():
    instances = catalog.full_assembly()
    report = {}
    camera_matrix = parts.camera_world_matrix(parts.CAMERA_TILT_DEG)
    failed = False
    for name, joints in poses().items():
        posed = assembly.posed(instances, joints)
        blocked, height = lidar_check(scene_mesh(posed, LIDAR_SELF))
        self_view = camera_check(scene_mesh(posed, CAMERA_SELF), camera_matrix)
        report[name] = {"lidar_blocked_deg": blocked, "camera_self_view_fraction": round(self_view, 4)}
        failed |= bool(blocked)
        print(
            f"{name:16s} lidar blocked rays: {len(blocked):3d}   camera image showing the robot: {100 * self_view:.1f} %"
        )
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=1))
    base_z = (assembly.step_to_base() @ np.array([0, 0, height, 1.0]))[2]
    lines = [
        "# Sensor field of view",
        "",
        "Generated by `strido_verify.sensor_fov` (ray casting on the posed CAD model).",
        "",
        f"LiDAR scan plane: {height:.1f} mm in the STEP frame = {base_z:.1f} mm above the hip axes "
        f"({base_z + 170 + 12:.0f} mm above ground when standing at 170 mm).",
        "",
        "| Pose | LiDAR rays blocked (of 720) | Camera image showing the robot |",
        "|---|---|---|",
    ]
    for name, row in report.items():
        lines.append(f"| {name} | {len(row['lidar_blocked_deg'])} | {100 * row['camera_self_view_fraction']:.1f} % |")
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines) + "\n")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
