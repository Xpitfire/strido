"""Markdown report of the fit check (docs/verification/fits.md)."""

from collections import Counter, defaultdict

from strido.workspace import path

from .fit_geometry import SeatFit
from .fits_model import ScrewFit

REPORT_MD = path("docs/verification/fits.md")
# ISO 273 clearance holes (fine / medium series) used for the drill recommendation
DRILL_MM = {"M2": (2.2, 2.4), "M2.5": (2.7, 2.9), "M3": (3.2, 3.4), "M5": (5.3, 5.5)}


# --------------------------------------------------------------------------- report


def write_markdown(screws: list[ScrewFit], seats: list[SeatFit]) -> None:
    status_count = Counter(s.status for s in screws)
    fits = Counter((p.fit, p.status) for s in screws for p in s.parts)
    terminations = Counter(s.termination for s in screws)
    lines = [
        "# Fits and tolerances",
        "",
        "Generated by `strido_verify.fits` from the assembled CAD (reference pose) and "
        "`hardware/verification/tolerances.yaml`. Every screw axis is sampled every 0.5 mm; each printed part around it "
        "is cut normal to the axis and its narrowest hole diameter classified.",
        "",
        f"**Screws:** {len(screws)} — ok {status_count['ok']}, warn {status_count['warn']}, **fail {status_count['fail']}**. "
        f"**Bearing seats:** {len(seats)} — fail {sum(s.status == 'fail' for s in seats)}.",
        "",
        "| Fit class | ok | warn | fail |",
        "|---|---|---|---|",
    ]
    for fit in (
        "clearance",
        "thread-forming",
        "tight passage",
        "passage",
        "bearing bore",
        "line-to-line",
        "solid",
        "oversize",
    ):
        lines.append(f"| {fit} | {fits[(fit, 'ok')]} | {fits[(fit, 'warn')]} | {fits[(fit, 'fail')]} |")
    lines += ["", "| Screw termination | Count |", "|---|---|"] + [
        f"| {k} | {v} |" for k, v in sorted(terminations.items())
    ]
    warn_parts: dict[tuple[str, str, str, float, str], int] = defaultdict(int)
    for screw in screws:
        for part in screw.parts:
            if part.status == "warn":
                warn_parts[(part.part, part.fit, screw.thread, part.hole_d_mm, part.note)] += 1
    if warn_parts:
        lines += [
            "",
            "## Warnings: what to do after printing",
            "",
            "Printed holes come out ~0.15 mm undersize. *Clearance / tight passage*: run the ISO 273 drill through once. "
            "*Thread-forming, weak grip*: tighten by feel; if a screw spins, harden the pilot with a drop of thin CA glue and re-drive (anaerobic thread locker does not cure on plastic and can crack PETG). *Short engagement*: do not over-tighten.",
            "",
            "| Part | Fit | Thread | CAD hole (mm) | Holes | Action |",
            "|---|---|---|---|---|---|",
        ]
        for (part, fit, thread, diameter, note), count in sorted(warn_parts.items()):
            fine, medium = DRILL_MM[thread]
            action = f"drill {fine} mm (or {medium} mm)" if fit in ("clearance", "tight passage") else note
            lines.append(f"| {part} | {fit} | {thread} | {diameter:.2f} | {count} | {action} |")
    failures = [(s, p) for s in screws for p in s.parts if p.status == "fail"]
    unsecured = [s for s in screws if s.termination == "none"]
    seat_failures = [s for s in seats if s.status == "fail"]
    lines += ["", "## Failures", ""]
    if not failures and not unsecured and not seat_failures:
        lines.append("None.")
    for screw, part in failures:
        lines.append(
            f"* `{screw.instance}` ({screw.joint}) in `{part.part}`: {part.fit}, hole {part.hole_d_mm} mm — {part.note}"
        )
    lines += [
        f"* `{s.instance}` ({s.joint}): nothing holds the screw (no nut, pilot or threaded part at the tip)"
        for s in unsecured
    ]
    lines += [
        f"* bearing `{s.bearing}` in `{s.part}`: seat {s.seat_d_mm} mm for OD {s.od_mm} mm" for s in seat_failures
    ]
    lines += ["", "## Bearing seats", "", "| Bearing | Part | OD (mm) | Seat (mm) | Result |", "|---|---|---|---|---|"]
    lines += [f"| {s.bearing} | {s.part} | {s.od_mm} | {s.seat_d_mm} | {s.status} |" for s in seats]
    REPORT_MD.parent.mkdir(parents=True, exist_ok=True)
    REPORT_MD.write_text("\n".join(lines) + "\n")
