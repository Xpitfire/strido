"""Generate the NT-X catalog assets of Strido from the CAD-derived simulation model.

Inputs (tracked, generated by `make models`):  models/mujoco/strido.xml, its link meshes in
ros2/strido_description/meshes, hardware/joint_limits.yaml (via the generated geometry), the
mass report. Outputs inside this package (shipped by the `ntx.assets` entry point):

    robots/strido.yaml            NT-X RobotSpec (joints in MCU order FL, FR, RL, RR x hip/thigh/calf)
    robots/models/strido.xml      robot-only MJCF, meshes resolved next to it
    robots/models/meshes/*.stl     visual meshes decimated for the Studio
    skills/strido-stand.yaml      pd-pose standing posture

`--check` fails if any output differs (drift gate in `make drift`).
"""

import argparse
import hashlib
import math
import re
import sys
from pathlib import Path
from typing import Any

import trimesh
import yaml

from strido.gait import stand_pose
from strido.geometry import LEG_NAMES
from strido.workspace import path

PACKAGE = Path(__file__).resolve().parent
SOURCE_MJCF = path("models/mujoco/strido.xml")
SOURCE_MESHES = path("ros2/strido_description/meshes")
MASS_REPORT = path("ros2/strido_description/config/mass_report.yaml")
ROBOT_YAML = PACKAGE / "robots/strido.yaml"
MODEL_DIR = PACKAGE / "robots/models"
SKILL_YAML = PACKAGE / "skills/strido-stand.yaml"
STUDIO_FACES_PER_LINK = 4000
JOINTS = ("hip", "thigh", "calf")
STAND_HEIGHT_M = 0.17
# SPT5435LV-180W at 6.0 V: 35 kg·cm stall torque, 0.14 s / 60 deg no-load speed (datasheet)
EFFORT_LIMIT_NM = round(35.0 * 9.80665 / 100.0, 3)
VELOCITY_LIMIT_RAD_S = round(math.radians(60.0) / 0.14, 2)
# `range="lo hi"` attribute of one named joint in the MJCF
JOINT_RANGE = r'<joint name="{name}"[^>]*range="([-\d.]+) ([-\d.]+)"'
# `kp="…"` / `kv="…"` attribute of the servo position default class
SERVO_GAIN = r'<position[^>]* {key}="([\d.]+)"'
# `meshdir="…"` attribute of the compiler element
MESHDIR = r'meshdir="[^"]*"'


def mjcf_text() -> str:
    text = SOURCE_MJCF.read_text()
    return re.sub(MESHDIR, 'meshdir="meshes"', text).replace(
        "GENERATED by strido_cad.models",
        "GENERATED by strido_ntx.build_assets from models/mujoco/strido.xml (strido_cad.models)",
    )


def robot_spec(mjcf: str) -> dict[str, Any]:
    kp = float(re.search(SERVO_GAIN.format(key="kp"), mjcf).group(1))  # type: ignore[union-attr]
    kd = float(re.search(SERVO_GAIN.format(key="kv"), mjcf).group(1))  # type: ignore[union-attr]
    joints = []
    for leg_index, leg in enumerate(LEG_NAMES):
        stand = stand_pose(STAND_HEIGHT_M)[3 * leg_index : 3 * leg_index + 3]
        for joint_index, joint in enumerate(JOINTS):
            name = f"{leg}_{joint}_joint"
            match = re.search(JOINT_RANGE.format(name=name), mjcf)
            if match is None:
                raise ValueError(f"{SOURCE_MJCF}: joint {name} has no range")
            joints.append(
                {
                    "name": name,
                    "sdk_index": 3 * leg_index + joint_index,
                    "group": f"{leg}_leg",
                    "lower": float(match.group(1)),
                    "upper": float(match.group(2)),
                    "velocity_limit": VELOCITY_LIMIT_RAD_S,
                    "effort_limit": EFFORT_LIMIT_NM,
                    "kp": kp,
                    "kd": kd,
                    "default": round(float(stand[joint_index]), 4),
                    "present": True,
                }
            )
    mass = yaml.safe_load(MASS_REPORT.read_text())["total_mass_kg"]
    digest = hashlib.sha256(mjcf.encode()).hexdigest()
    return {
        "id": "strido",
        "label": "Strido",
        "vendor": "strido",
        "family": "quadruped",
        "base": "floating",
        "height_m": 0.26,
        "mass_kg": round(float(mass), 3),
        "joints": joints,
        "end_effectors": {},
        "feet": [f"{leg}_foot" for leg in LEG_NAMES],
        "root_body": "base_link",
        "anchor_body": "base_link",
        "capabilities": ["locomotion"],
        "sdk": {"protocol": "none", "motor_slots": 12},
        "model": {
            "source": "https://github.com/Xpitfire/strido",
            "license": "Apache-2.0",
            "path": "robots/models/strido.xml",
            "sha256": digest,
            "notes": "Generated from the verified Strido CAD (strido_cad.models): link masses/inertias from the "
            "printed-part volumes and datasheet masses, joint ranges from the collision sweep, SPT5435LV servos.",
        },
        "hardware_status": "unverified",
        "notes": [
            "Joint order = MCU order: FL, FR, RL, RR x (hip, thigh, calf); sdk_index is the firmware joint slot.",
            "Hobby position servos: no joint position/velocity feedback on hardware (q = clamped command).",
            "Hardware transport: strido_ntx.serial_port.StridoSerialPort (registry robot adapter 'strido-serial').",
        ],
    }


def stand_skill(spec: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": "strido-stand",
        "label": "Strido standing posture",
        "robot_ids": [spec["id"]],
        "kind": "pose-tracking",
        "capabilities": ["pose.hold"],
        "description": "Holds the 170 mm standing posture (hip axes above the feet) with the servo PD gains of the model. "
        "A quadruped is statically stable: no gantry. Hardware sessions need a base estimate first (the serial port has no odometry).",
        "evidence_tier": "component",
        "evidence": "make ntx-smoke: stands upright in NT-X MuJoCo for 2 s",
        "runtime": {"name": "pd-pose", "options": {"control_dt": 0.02}},
        "command": {"kind": "pose", "rate_limit": 1.0, "groups": []},
        "default_scene": "open-floor",
        "safe_hold": {"mode": "hold-posture", "description": "Keep the standing posture."},
        "provenance": {
            "source": "https://github.com/Xpitfire/strido",
            "license": "Apache-2.0",
            "notes": "Standing pose from strido.gait.stand_pose (0.17 m body height).",
        },
    }


def studio_mesh(source: Path) -> bytes:
    mesh: trimesh.Trimesh = trimesh.load_mesh(source)
    if len(mesh.faces) > STUDIO_FACES_PER_LINK:
        mesh = mesh.simplify_quadric_decimation(face_count=STUDIO_FACES_PER_LINK)
    exported: bytes = trimesh.exchange.stl.export_stl(mesh)
    return exported


def outputs() -> dict[Path, bytes]:
    mjcf = mjcf_text()
    spec = robot_spec(mjcf)
    files = {
        MODEL_DIR / "strido.xml": mjcf.encode(),
        ROBOT_YAML: (
            "# GENERATED by strido_ntx.build_assets - do not edit.\n" + yaml.safe_dump(spec, sort_keys=False, width=140)
        ).encode(),
        SKILL_YAML: (
            "# GENERATED by strido_ntx.build_assets - do not edit.\n"
            + yaml.safe_dump(stand_skill(spec), sort_keys=False, width=140)
        ).encode(),
    }
    for stl in sorted(SOURCE_MESHES.glob("*.stl")):
        files[MODEL_DIR / "meshes" / stl.name] = studio_mesh(stl)
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated assets are stale")
    args = parser.parse_args()
    files = outputs()
    # Decimated meshes are binary floats (platform-dependent rounding): the drift gate compares the
    # text assets byte for byte and only requires every mesh to exist.
    stale = [
        target
        for target, content in files.items()
        if not target.is_file() or (target.suffix != ".stl" and target.read_bytes() != content)
    ]
    if not args.check:
        stale = [target for target, content in files.items() if not target.is_file() or target.read_bytes() != content]
    if args.check:
        for target in stale:
            print(f"stale: {target.relative_to(PACKAGE)} (run python -m strido_ntx.build_assets)")
        if stale:
            sys.exit(1)
        print(f"NT-X assets up to date ({len(files)} files)")
        return
    for target in stale:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content := files[target])
        print(f"wrote {target.relative_to(PACKAGE)} ({len(content)} bytes)")


if __name__ == "__main__":
    main()
